"""kushwind/vfp2js.py: the LINE-BY-LINE transcription of 0x232e24 (a 4x4 matrix inverse: out r0, in r1) into JS -- every instruction
one statement, single registers in a Float32Array (each write rounds to f32 as the VFP does), vmla / vmls / vnmul unfused (the
product rounded, then the sum / negation), the 8-byte stack frame as two slots. Its one branch: vcmpe det, #0 / bne -- a zero
determinant copies the identity (GOT 0x1832afc) to out. Output: docs/render/rom/effect/rom-inv44.js.
    python vfp2js.py > ../../../docs/render/rom/effect/rom-inv44.js
Checked bit-exact against the ROM run on unicorn by inv44check.py / inv44check.mjs."""
import sys, re
sys.path.insert(0, r'C:\MHGU-Extract\efx')
import armdis, capstone
md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)
LO, HI = 0x232e24, 0x23328c
ins = list(md.disasm(armdis.TEXT[LO:HI], LO))
S = lambda r: int(r[1:])
def mem(op):
    m = re.match(r'\[(\w+)(?:, #(-?0x[0-9a-f]+|\d+))?\]', op)
    return m.group(1), int(m.group(2), 0) if m.group(2) else 0
out = []
emit = out.append
for i in ins:
    a, mn, op = i.address, i.mnemonic, i.op_str
    ops = [x.strip() for x in op.split(',', 2)] if op else []
    if '[' in op: ops = [op.split(',')[0].strip(), op[op.index('['):]]
    tag = '   // %06x %s %s' % (a, mn, op)
    if mn in ('vpush', 'vpop', 'sub', 'add', 'vmrs') : emit('  ' + tag.strip()); continue   # frame / flags: no data effect here
    if mn == 'vldr':
        b, o = mem(ops[1]); src = 'stk[%d]' % (o // 4) if b == 'sp' else 'm.f32(%s + %d)' % (b, o)
        emit('  s[%d] = %s;%s' % (S(ops[0]), src, tag)); continue
    if mn == 'vstr':
        b, o = mem(ops[1])
        emit(('  stk[%d] = s[%d];' % (o // 4, S(ops[0])) if b == 'sp' else '  m.wf32(%s + %d, s[%d]);' % (b, o, S(ops[0]))) + tag); continue
    if mn in ('vmul.f32', 'vdiv.f32'):
        emit('  s[%d] = s[%d] %s s[%d];%s' % (S(ops[0]), S(ops[1]), '*' if mn == 'vmul.f32' else '/', S(ops[2]), tag)); continue
    if mn == 'vmla.f32': emit('  s[%d] = s[%d] + F(s[%d] * s[%d]);%s' % (S(ops[0]), S(ops[0]), S(ops[1]), S(ops[2]), tag)); continue
    if mn == 'vmls.f32': emit('  s[%d] = s[%d] - F(s[%d] * s[%d]);%s' % (S(ops[0]), S(ops[0]), S(ops[1]), S(ops[2]), tag)); continue
    if mn == 'vnmul.f32': emit('  s[%d] = -F(s[%d] * s[%d]);%s' % (S(ops[0]), S(ops[1]), S(ops[2]), tag)); continue
    if mn == 'vneg.f32': emit('  s[%d] = -s[%d];%s' % (S(ops[0]), S(ops[1]), tag)); continue
    if mn == 'vmov.f32':
        if ops[1].startswith('#'): emit('  s[%d] = %s;%s' % (S(ops[0]), float(ops[1][1:]), tag))
        else: emit('  s[%d] = s[%d];%s' % (S(ops[0]), S(ops[1]), tag))
        continue
    if mn == 'vcmpe.f32': emit('  const det0 = s[%d] === 0;%s' % (S(ops[0]), tag)); continue
    if mn == 'bne': emit('  if (!det0){' + tag); continue
    if mn == 'ldr' and '[pc' in op: emit('  ' + tag.strip() + ' (the identity: GOT 0x1832afc)'); continue
    if mn == 'ldr' and ops[1].startswith('[pc'): continue
    if mn == 'ldr' and re.match(r'\[r1, pc\]|\[pc, r1\]', ops[1]): continue
    if mn in ('ldr', 'str'):
        b, o = mem(ops[1])
        if mn == 'ldr': emit('  R.%s = m.u32(%s + %d);%s' % (ops[0], 'I' if b == 'r1' and a > 0x232f28 and a < 0x232fb4 else b, o, tag))
        else: emit('  m.w32(%s + %d, R.%s);%s' % (b, o, ops[0], tag))
        continue
    if mn == 'b': emit('  return;' + tag); continue
    if mn == 'bx': emit('  ' + tag.strip()); continue
    raise SystemExit('unhandled %x %s %s' % (a, mn, op))
body = '\n'.join(out)
# the zero-determinant copy runs between the bne and the nonzero target: put it first, as the else of the branch
zero_lo = body.index('  if (!det0){')
head, rest = body[:zero_lo], body[zero_lo:]
lines = rest.split('\n')
# lines[0] is the `if (!det0){`; the copy follows until `return;`; the nonzero path after it
k = next(j for j, l in enumerate(lines) if l.strip().startswith('return;'))
copy, nonzero = lines[1:k + 1], lines[k + 1:]
print('''// GENERATED by dev/archive/kushwind/vfp2js.py -- do not edit. 0x232e24(out, a): the ROM's 4x4 inverse, line by line (single
// precision, unfused multiply-adds as the VFP's vmla / vmls). A zero determinant copies the identity (GOT 0x1832afc -> [I]).
// Checked bit-exact against the ROM itself run on unicorn (dev/archive/kushwind/inv44check.py + inv44check.mjs).
const F = Math.fround;
export function inv232e24(m, out, a, I){
  const s = new Float32Array(32), stk = new Float32Array(2), R = {};
  const r0 = out, r1 = a;
''' + head.replace('r0 +', 'r0 +').rstrip())
print('  if (det0){')
print('\n'.join('  ' + l for l in copy if not l.strip().startswith('//')))
print('  }')
print('\n'.join(l for l in nonzero))
print('}')

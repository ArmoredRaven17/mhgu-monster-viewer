"""hypermotion/mkhypermotion.py (hyper-motion lane, 2026-10-27): docs/hyper-motion.json, the viewer's Hyper motion table.
Per monster, per .mdd file (`normal` below G, `g` at G: the loader 0x4bd64 by e+0xb736):
  * `hooks`: per held pair (keyed as index.html's state.hyper: the group-0 ID, then the group-1 ID, a missing group left out) and
    motion ('L<list> M<n>' = e+0x4b4): `rates` [[frame, x]..] -- the factor the class hook passes 0xb07b4 (P+0x398), the last call of
    that frame, kept where it changes; it holds to the motion's end (setMotion 0xafce8 puts P+0x398 back to 1.0) -- and `bursts`
    [[frame, ID]..] (0xca4e0(e, ID): u 1310 + ID). From hookemu.py (each class's own vt+0x1ec / +0x1f0 under unicorn).
  * `modify`: per aura ID (the .mdd's ModifyData ActionElements, mpRandTables[0]): [ActionStatus, ActionNo, Rate, MotionSpeedRate, (+ AttackRate, PowerRate: the hit object 0x1689b0)
    MotionSpeedRateLimit] -- consumed by vt+0x16c 0xc9e88 at every action set (0x767c8): BOTH groups' elements held (e+0xca94,
    e+0xcaa8), group 0's entries first, then group 1's, the first whose (status, number) is the new action's and whose Rate beats
    the roll (e+0x73e8 % 100 < Rate) -> e+0xb724 = MotionSpeedRate, e+0xb728 = Limit; then vt+0x368 0xc046c: P+0x38c = base x
    e+0xb724, clamped to e+0xb728 -- the factor every setMotion of that action starts from (0xafdd0) and 0xb07b4 keeps (0xb082c).
  * `actMotions`: per ModifyData action, the motions its action main sets (modmotions.py, zg/tracec.py) -- for a play whose action
    the viewer does not name.
  * `shells`: per aura ID (ShellElements): [ShellClassNumber, AttackRate, ScaleRate] -- consumed by the shell hit registration
    0x43a8b0 / 0xcaa30 (rom-map row `0x43a8b0` second half). Listed, NOT applied by the viewer (no shell carries the aura ID yet).
   python dev/archive/hypermotion/mkhypermotion.py   (reads dev/archive/hypermotion/hooks.json)"""
import subprocess, re, json, os, sys, glob
XFS = r'C:\MHGU-Extract\efx\agents\state-fx-scratch\xfsdata.py'
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))


def parse(path):
    t = subprocess.run([sys.executable, XFS, path], capture_output=True, text=True).stdout.split('\n')
    mode, mods, shells, cur, curs = None, {}, {}, None, None
    for l in t:
        s = l.strip()
        if s.startswith('mpActionElements'): mode = 'a'
        elif s.startswith('mpShellElements'): mode = 's'
        elif s.startswith('mPartsChangeData') or s.startswith('mPartsAuraData'): mode = None
        m = re.match(r'(\w+)(\[\d+\])? = (.*)$', s)
        if not m or mode is None: continue
        k, v = m.group(1), m.group(3)
        try: v = float(v) if '.' in v else int(v)
        except Exception: pass
        if mode == 'a':
            if k == 'DouMouKaID': cur = mods.setdefault(str(v), [])
            elif k == 'ActionStatus' and cur is not None: cur.append({'st': v})
            elif cur: cur[-1][k] = v
        else:
            if k == 'DouMouKaID': curs = shells.setdefault(str(v), [])
            elif k == 'ShellClassNumber' and curs is not None: curs.append({'cls': v})
            elif curs: curs[-1][k] = v
    mods = {i: [[e['st'], e['ActionNo'], e['Rate'], e['MotionSpeedRate'], e['MotionSpeedRateLimit'], e['AttackRate'], e['PowerRate']] for e in r] for i, r in mods.items()}
    shells = {i: [[e['cls'], e['AttackRate'], e['ScaleRate']] for e in r] for i, r in shells.items() if r}
    return mods, shells


hooks = json.load(open(os.path.join(HERE, 'hooks.json')))
# the motions each ModifyData action sets (modmotions.py, the class's action main under zg/tracec.py)
MM = json.load(open(os.path.join(HERE, 'modmotions.json'))) if os.path.exists(os.path.join(HERE, 'modmotions.json')) else {}
out = {'_about': 'GU Hyper motion (dev/hyper-states.md 6; generated by dev/archive/hypermotion/mkhypermotion.py): per monster and .mdd '
       'file, `hooks` [pair]["L<list> M<n>"] = {rates: [[frame, x]..] (0xb07b4, held to the motion end), bursts: [[frame, ID]..] '
       '(0xca4e0: u 1310 + ID)}; `modify` [ID] = [[ActionStatus, ActionNo, Rate, MotionSpeedRate, Limit]..] (vt+0x16c 0xc9e88 -> '
       'vt+0x368 0xc046c: P+0x38c); `actMotions` ["st:0xno"] = the motions that action sets (modmotions.py); `shells` [ID] = [[ShellClassNumber, AttackRate, ScaleRate]..] (0x43a8b0, not applied).'}
for mid, h in hooks.items():
    if 'error' in h: continue
    o = {'class': h['class'], 'hook': h['hook'], 'actMotions': MM.get(mid, {})}
    for fk, suf in (('normal', ''), ('g', '_g')):
        if fk not in h: continue
        f = glob.glob(r'C:\MHGU-Extract\scratch-em\%s\enemy\dou_mou_ka\%s_doumouka%s.mdd' % (mid, mid, suf))
        mods, shells = parse(f[0]) if f else ({}, {})
        o[fk] = {'hooks': {k: {m: {'rates': c['rates'], 'bursts': c['bursts']} for m, c in v.items()} for k, v in h[fk]['pairs'].items()}, 'modify': mods, 'shells': shells}
    out[mid] = o
json.dump(out, open(os.path.join(ROOT, 'docs', 'hyper-motion.json'), 'w'), separators=(',', ':'))
print('wrote docs/hyper-motion.json', os.path.getsize(os.path.join(ROOT, 'docs', 'hyper-motion.json')))
rates = sorted({e[2] for m in out.values() if isinstance(m, dict) for fk in ('normal', 'g') if fk in m for r in m[fk]['modify'].values() for e in r})
print('modify Rate values', rates)

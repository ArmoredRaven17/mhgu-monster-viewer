"""arm_export.py [--apply]: Nakarkos's tentacles' OWN PSL records (board PHASE 3), exported per arm as a pseudo-monster the
viewer runs a second effect runtime on -- 'em084_00_left' / 'em084_00_right', the attached bodies' piece names (render/monster.js
ROM_ATTACHED_BODY). In the game each arm is a unit of its own class (uEmOstgaloaArm): its PSL walker reads ITS motion and frame
on its own lists em084_00_l_N / em084_00_r_N, its records come from its own pels (em084_00u_l / em084_00c_l, _r), and they
hang from its joints. add_effects.plan() already reads those blocks and marks them "entity motion: not bound"; this takes
the ok ones:
  * docs/effects/<pseudo>.json -- add_effects.export() of the side's records (arrays as plan() named them);
  * CLIP_EFFECTS[<pseudo>] in render/monster.js -- keyed 'L<arm list> Motion[N]' (e.g. 'Ll_0 Motion[2]'), the arm list ids
    as monsters.json names them, so clipEffectsFor(pseudo, clip, armList) finds them; only motions the viewer carries,
    with the frame test plan() makes.
Without --apply: the table of what would be exported."""
import sys, os, collections
sys.path.insert(0, r'C:\MHGU-Extract\efx')
os.chdir(r'C:\MHGU-Extract\efx')
import add_effects as A
mon = 'em084_00'
cfg, entry, rows, records = A.plan(mon)
lists = {l['id']: {c['clip'].replace('_loop', '').replace('_start', ''): None for c in l['clips']} for l in entry['lists']}
# viewer frames per arm clip (a split clip: its _start + _loop)
frames_of = {}
for l in entry['lists']:
    fr = collections.defaultdict(float)
    for c in l['clips']:
        fr[c['clip'].replace('_loop', '').replace('_start', '')] += c['dur']
    frames_of[l['id']] = {k: round(v * A.PSL_FPS) for k, v in fr.items()}
side_of = {'l': 'em084_00_left', 'r': 'em084_00_right'}
per = {s: collections.OrderedDict() for s in side_of}
blocks = {s: collections.defaultdict(list) for s in side_of}
skipped = []
for (lst, slot, frames, bit, pel, eff, r, on, clip_state, state, types) in rows:
    if not isinstance(lst, str): continue
    s = lst.split('_')[0]
    if s not in side_of: continue
    if r is None or state.startswith(('refused', 'missing')):
        skipped.append((lst, slot, bit, pel, eff, state)); continue
    have = frames_of.get(lst, {}).get('Motion[%d]' % slot)
    if have is None or abs(have - frames) > 1:
        skipped.append((lst, slot, bit, pel, eff, 'the viewer has no %s Motion[%d] of %d frames (has %s)' % (lst, slot, frames, have))); continue
    per[s].setdefault((pel, eff, r['array']), r)
    blocks[s]['L%s Motion[%d]' % (lst, slot)].append((bit, r['efl'], eff, on, frames))
for s, pseudo in side_of.items():
    print('%s: %d records, %d motions' % (pseudo, len(per[s]), len(blocks[s])))
for k in skipped: print('  skipped', k)
if '--apply' not in sys.argv: raise SystemExit(0)
for s, pseudo in side_of.items():
    d = A.export(pseudo, per[s])
    if d is None: raise SystemExit('nothing exported for ' + pseudo)
    exported = {(e['efl'].split('/')[-1], e['record']['key']) for e in d['effects'] if e.get('record') and e.get('when') == 'clip'}
    lines = []
    for key in sorted(blocks[s], key=lambda k: (k.split(' ')[0], int(k.split('[')[1][:-1]))):
        b = blocks[s][key]
        out = ["{ bit: %d, efl: '%s', key: %d, on: [%s] }" % (bit, efl + '.efl', eff, ', '.join('[%d, %d]' % tuple(x) for x in on))
               for bit, efl, eff, on, fr in b if (efl + '.efl', eff) in exported]
        if out: lines.append("    '%s': { frames: %d, bits: [%s] }," % (key, b[0][4], ', '.join(out)))
    head = ("  // NAKARKOS's %s TENTACLE (%s): its OWN PSL blocks (em084_00_%s_N.psl), GENERATED by <scratchpad>/zg/arm_export.py over\n"
            "  // C:\\MHGU-Extract\\efx\\add_effects.py's plan -- keyed by the arm's own lists; run on its own effect runtime (index.html\n"
            "  // driveArmEffects), its records from its own pels." % ('LEFT' if s == 'l' else 'RIGHT', pseudo, s))
    text = '\n'.join([head, '  %s: {' % pseudo] + lines + ['  },'])
    A.write_clip_block(pseudo, text)
    print('CLIP_EFFECTS: %d motions for %s' % (len(lines), pseudo))

"""mkhyperauras.py (2026-10-25, effects lane): hyper.json (hypermdd.py's parse of both .mdd files per monster) -> docs/hyper-auras.json.

WHICH FILE LOADS (READ 2026-10-25): the loader 0x4bd64 reads the enemy byte e+0xb736 (0x4bd80..0x4bd90): 0 -> resource-list column 0x26,
else column 0x27, then table[monster][column] (GOT 0x4be34) -> the path index -> 0x152530(manager, index, rEmDouMouKaData's DTI, getDTI
0x51400) -> the resource handed to the class (vt+0x150 0xca68c stores it at e+0xca80). e+0xb736 is written by 0x6f194 at 0x6f1c0..0x6f1d8:
`bl 0x3a8430 (the quest rank) / cmp r0, #4 / movwgt r1, #1 / strb r1, [e+0xb736]` -- G rank (rank > 4) loads column 0x27, below it 0x26.
The monster's resource list in .rodata pairs (path hash, type hash): Rathian's at 0x15d99d0 holds crc("enemy\\dou_mou_ka\\em001_00_doumouka")
then crc("enemy\\dou_mou_ka\\em001_00_doumouka_G"), both typed rEmDouMouKaData (0x1f149aec). So: `normal` below G, `g` at G.

Per monster: { normal: {file, firstRandom, auras} | null, g: {...} | null }; an aura is {id, group, part, key (1300 + id), joint, exported, meat (its MeatChange_Group damage slots), meatBias}.
The joint comes from the record's triage row (dev/effects-triage/<id>.md), `exported` from docs/effects/<id>.json.
    python hypermdd.py > hyper.json   (beside this script; hyper.json, 293 KB, is regenerated, not archived: EXCLUDED.md)
    python mkhyperauras.py"""
import json, os, re
V = r'C:\MHGU-Extract\MHGU-Monster-Viewer'
H = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'hyper.json')))
def joints(mon):
    out = {}
    p = os.path.join(V, 'dev', 'effects-triage', mon + '.md')
    if os.path.exists(p):
        for l in open(p, encoding='utf8'):
            c = [x.strip() for x in l.split('|')]
            if len(c) > 6 and c[1] == 'u' and c[2] == 'UNIQUE' and c[3].isdigit():
                try: out[int(c[3])] = int(c[5])
                except ValueError: pass
    return out
def exported(mon):
    p = os.path.join(V, 'docs', 'effects', mon + '.json')
    if not os.path.exists(p): return set()
    return {e['record']['key'] for e in json.load(open(p, encoding='utf8'))['effects'] if e['record']['pel'].endswith('u')}
out = {'_about': 'GU Hyper (rEmDouMouKaData; dev/hyper-states.md): per monster the aura table of each of its two .mdd files -- `normal` '
                 '(<id>_doumouka.mdd, loaded below G rank) and `g` (<id>_doumouka_g.mdd, loaded at G rank: e+0xb736 = quest rank > 4, '
                 '0x6f1c0..0x6f1d8; the loader 0x4bd64 takes resource column 0x26 / 0x27 by it). An aura: DouMouKaID, SpecificPartsGroup '
                 '(0 / 1: one aura per group at a time), SpecificParts (the part), the u record 1300 + ID (0xca1f8: u id 47 + ID through the '
                 'base table 0x159c7fc) and its joint; `meat` / `meatBias` its MeatChange_Group slots and MeatChange_SpecificParts_Bias (vt+0x18c 0xca900, read by the deflect classifier 0x16d800). Generated by dev/archive/cen/mkhyperauras.py from hypermdd.py\'s hyper.json.'}
for mon, files in H.items():
    if not files: continue
    J, X = joints(mon), exported(mon)
    row = {'normal': None, 'g': None}
    for f, d in files.items():
        kind = 'g' if f.endswith('_g.mdd') else 'normal'
        if not d['auras']: continue
        row[kind] = {'file': f, 'firstRandom': d['firstRandom'],
                     'auras': [{'id': a['id'], 'group': a.get('group'), 'part': a.get('part'), 'key': 1300 + a['id'],
                                'joint': J.get(1300 + a['id']), 'exported': (1300 + a['id']) in X,
                                # MeatChange_Group[0..3] (255 = none, dropped) and MeatChange_SpecificParts_Bias: vt+0x18c 0xca900
                                'meat': a.get('meat', []), 'meatBias': a.get('meatBias', 1)} for a in d['auras']]}
    if row['normal'] or row['g']: out[mon] = row
json.dump(out, open(os.path.join(V, 'docs', 'hyper-auras.json'), 'w'), indent=1)
print(len(out) - 1, 'monsters;', sum(1 for k, v in out.items() if k != '_about' and v['normal'] and v['g'] and v['normal']['auras'] != v['g']['auras']), 'differ by rank;',
      sum(1 for k, v in out.items() if k != '_about' and not v['normal']), 'G only')

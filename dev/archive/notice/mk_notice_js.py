# Prints the NOTICE_SENSE table; the module's code around it is hand-written (paste between the GENERATED markers).
import json, sys
d = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'sense.json'))
def g(x):
    return ('%.6g' % x) if isinstance(x, float) else str(x)
print('// GENERATED by dev/archive/notice/mk_notice_js.py from notice_sense.py: id -> { f: P+0x1a8 (0x159c2dc), mem: [reload, timeout] (dtbase +0x8c),')
print('//   s: the dttune sense records [joint, turn +4, turn +6, near, range, up, down, half-yaw, half-pitch] (P+0x249 picks one; 0 at spawn) }')
print('export const NOTICE_SENSE = {')
for k in sorted(d):
    v = d[k]
    s = ', '.join('[' + ', '.join(g(x) for x in r[:9]) + ']' for r in v['sense'])
    print("  %s: { f: 0x%x, mem: [%d, %d], s: [%s] }," % (k, v['flags1a8'], v['mem'][0], v['mem'][1], s))
print('};')
